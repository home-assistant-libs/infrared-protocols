# The key and frame count each Emanuel capture decodes to. Every button uses
# frame head 110 and custom code 00. The receiver broke one frame in two of
# them: a noise pulse ahead of a button frame in the medium speed capture,
# and a split final mark in the first start frame of the light on capture.
# Those frames do not decode and are left out of the vote.
EMANUEL_DECODED = [
    pytest.param(EMANUEL_HI, SymphonyKey.K1, 2, id="hi"),
    pytest.param(EMANUEL_MED, SymphonyKey.K3, 5, id="med"),
    pytest.param(EMANUEL_LIGHT_ON, SymphonyKey.K4, 5, id="light_on"),
    pytest.param(EMANUEL_FAN_OFF, SymphonyKey.K5, 6, id="fan_off"),
    pytest.param(EMANUEL_LIGHT_OFF, SymphonyKey.K6, 5, id="light_off"),
    pytest.param(EMANUEL_LOW, SymphonyKey.K7, 4, id="low"),
]


def _fields(command: SymphonyCommand) -> tuple[int, int, int, bool, int]:
    """Return everything a decode reports, for one comparison per test."""
    return (
        command.frame_head,
        command.custom_code,
        command.control_word,
        command.start_frames,
        command.repeat_count,
    )


@pytest.mark.parametrize(("pronto", "key", "repeat_count"), MADEIRA_DECODED)
def test_symphony_command_decodes_madeira_capture(
    pronto: str, key: SymphonyKey, repeat_count: int
) -> None:
    """Every Madeira button decodes to its key; the start frames are dropped."""
    timings = ProntoCommand.from_pronto_hex(pronto).get_raw_timings()
    decoded = SymphonyCommand.from_raw_timings(timings)
    assert decoded is not None
    assert _fields(decoded) == (0b110, 0b00, key, False, repeat_count)


